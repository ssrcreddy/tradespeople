// Data model (design §12). Every tenant table carries business_id and gets an
// RLS policy in drizzle/0001_rls.sql. Money is integer cents, quantities are
// integer thousandths, rates are parts per million.
import { sql } from "drizzle-orm";
import {
  pgTable, pgEnum, uuid, text, integer, boolean, timestamp, jsonb, date, char,
  bigserial, numeric, primaryKey, unique, uniqueIndex, index, check,
} from "drizzle-orm/pg-core";
import type { TaxComponent } from "@qa/shared";

const id = () => uuid("id").primaryKey().defaultRandom();
const businessId = () => uuid("business_id").notNull().references(() => businesses.id, { onDelete: "cascade" });
const createdAt = () => timestamp("created_at", { withTimezone: true }).notNull().defaultNow();
const updatedAt = () => timestamp("updated_at", { withTimezone: true }).notNull().defaultNow();

// ---------- enums ----------
export const trade = pgEnum("trade", ["electrical"]);
export const memberRole = pgEnum("member_role", ["owner", "member"]);
export const priceBookKind = pgEnum("price_book_kind", ["labour", "material", "callout", "fixed_job", "assembly"]);
export const lineUnit = pgEnum("line_unit", ["each", "hour", "flat", "metre", "foot"]);
export const jobSource = pgEnum("job_source", ["email_forward", "paste", "upload", "share", "site_notes", "manual"]);
export const jobStatus = pgEnum("job_status", ["received", "extracting", "draft_ready", "in_review", "needs_info", "extraction_failed", "closed"]);
export const quoteStatus = pgEnum("quote_status", ["draft", "approved", "sending", "sent", "accepted", "declined", "expired", "superseded"]);
export const sourceKind = pgEnum("source_kind", ["text", "photo", "manual", "assembly"]);
export const sentVia = pgEnum("sent_via", ["email", "manual_share"]);
export const invoiceKind = pgEnum("invoice_kind", ["deposit", "final"]);
export const invoiceStatus = pgEnum("invoice_status", ["issued", "sending", "sent", "paid", "void"]);
export const inboundDisposition = pgEnum("inbound_disposition", ["job", "quarantined", "dropped", "rate_limited"]);
export const notifyChannel = pgEnum("notify_channel", ["email", "push"]);
export const emailEventType = pgEnum("email_event_type", ["delivered", "bounced", "complained", "opened"]);

// ---------- Better Auth core tables (not tenant-scoped; no RLS) ----------
export const user = pgTable("user", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  email: text("email").notNull().unique(),
  emailVerified: boolean("email_verified").notNull().default(false),
  image: text("image"),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
});

export const session = pgTable("session", {
  id: text("id").primaryKey(),
  expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
  token: text("token").notNull().unique(),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
  ipAddress: text("ip_address"),
  userAgent: text("user_agent"),
  userId: text("user_id").notNull().references(() => user.id, { onDelete: "cascade" }),
});

export const account = pgTable("account", {
  id: text("id").primaryKey(),
  accountId: text("account_id").notNull(),
  providerId: text("provider_id").notNull(),
  userId: text("user_id").notNull().references(() => user.id, { onDelete: "cascade" }),
  accessToken: text("access_token"),
  refreshToken: text("refresh_token"),
  idToken: text("id_token"),
  accessTokenExpiresAt: timestamp("access_token_expires_at", { withTimezone: true }),
  refreshTokenExpiresAt: timestamp("refresh_token_expires_at", { withTimezone: true }),
  scope: text("scope"),
  password: text("password"),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
});

export const verification = pgTable("verification", {
  id: text("id").primaryKey(),
  identifier: text("identifier").notNull(),
  value: text("value").notNull(),
  expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
});

// ---------- tenancy ----------
export const businesses = pgTable("businesses", {
  id: uuid("id").primaryKey(),                       // generated by the app so RLS can be set before insert
  name: text("name").notNull(),
  trade: trade("trade").notNull().default("electrical"),
  taxComponents: jsonb("tax_components").$type<TaxComponent[]>().notNull().default([]),
  currency: char("currency", { length: 3 }).notNull().default("CAD"),
  timezone: text("timezone").notNull().default("America/Toronto"),
  locale: text("locale").notNull().default("en-CA"),
  logoPath: text("logo_path"),
  replyToEmail: text("reply_to_email"),
  senderAllowlist: text("sender_allowlist").array().notNull().default(sql`'{}'::text[]`),
  intakeToken: text("intake_token").notNull().unique(),
  termsDays: integer("terms_days").notNull().default(14),
  quoteExpiryDays: integer("quote_expiry_days").notNull().default(30),
  depositPctDefault: integer("deposit_pct_default").notNull().default(0),
  collapseAssemblies: boolean("collapse_assemblies").notNull().default(true),
  nextQuoteNo: integer("next_quote_no").notNull().default(1),
  nextInvoiceNo: integer("next_invoice_no").notNull().default(1),
  createdAt: createdAt(),
}, (t) => [
  check("businesses_deposit_pct", sql`${t.depositPctDefault} between 0 and 100`),
  check("businesses_terms", sql`${t.termsDays} between 0 and 365 and ${t.quoteExpiryDays} between 1 and 365`),
]);

export const memberships = pgTable("memberships", {
  id: id(),
  userId: text("user_id").notNull().references(() => user.id, { onDelete: "cascade" }),
  businessId: businessId(),
  role: memberRole("role").notNull(),
  createdAt: createdAt(),
}, (t) => [unique("memberships_user_business").on(t.userId, t.businessId)]);

export const customers = pgTable("customers", {
  id: id(),
  businessId: businessId(),
  name: text("name").notNull(),
  email: text("email"),
  phone: text("phone"),
  siteAddress: text("site_address"),
  createdAt: createdAt(),
}, (t) => [
  uniqueIndex("customers_business_email").on(t.businessId, sql`lower(${t.email})`).where(sql`${t.email} is not null`),
  check("customers_contact", sql`${t.email} is not null or ${t.phone} is not null`),
]);

// ---------- price book ----------
export const priceBookItems = pgTable("price_book_items", {
  id: id(),
  businessId: businessId(),
  kind: priceBookKind("kind").notNull(),
  name: text("name").notNull(),
  description: text("description"),
  unit: lineUnit("unit").notNull(),
  costCents: integer("cost_cents"),
  markupPpm: integer("markup_ppm"),
  rateCents: integer("rate_cents"),                  // null = not set yet; null for assemblies
  aliases: text("aliases").array().notNull().default(sql`'{}'::text[]`),
  active: boolean("active").notNull().default(true),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
}, (t) => [
  index("price_book_business_active").on(t.businessId, t.active),
  check("price_book_money", sql`coalesce(${t.rateCents}, 0) >= 0 and coalesce(${t.costCents}, 0) >= 0 and coalesce(${t.markupPpm}, 0) >= 0`),
  check("price_book_assembly_no_rate", sql`${t.kind} <> 'assembly' or ${t.rateCents} is null`),
]);

export const assemblyComponents = pgTable("assembly_components", {
  businessId: businessId(),
  assemblyId: uuid("assembly_id").notNull().references(() => priceBookItems.id, { onDelete: "cascade" }),
  componentId: uuid("component_id").notNull().references(() => priceBookItems.id, { onDelete: "restrict" }),
  qtyMilli: integer("qty_milli").notNull(),
  sort: integer("sort").notNull().default(0),
}, (t) => [
  primaryKey({ columns: [t.assemblyId, t.componentId] }),
  check("assembly_components_qty", sql`${t.qtyMilli} > 0`),
  check("assembly_components_not_self", sql`${t.assemblyId} <> ${t.componentId}`),
]);

// ---------- intake ----------
export const inboundMessages = pgTable("inbound_messages", {
  id: id(),
  businessId: uuid("business_id").references(() => businesses.id, { onDelete: "cascade" }), // null = unknown token
  providerMessageId: text("provider_message_id").notNull().unique(),
  rawObjectKey: text("raw_object_key").notNull(),
  fromAddr: text("from_addr").notNull(),
  disposition: inboundDisposition("disposition").notNull(),
  receivedAt: timestamp("received_at", { withTimezone: true }).notNull().defaultNow(),
});

export const jobs = pgTable("jobs", {
  id: id(),
  businessId: businessId(),
  customerId: uuid("customer_id").references(() => customers.id, { onDelete: "set null" }),
  inboundMessageId: uuid("inbound_message_id").references(() => inboundMessages.id),
  source: jobSource("source").notNull(),
  originalText: text("original_text").notNull().default(""),
  originalFiles: jsonb("original_files").$type<{ key: string; sha256: string; contentType: string }[]>().notNull().default([]),
  providerMessageId: text("provider_message_id").unique(),
  status: jobStatus("status").notNull().default("received"),
  createdAt: createdAt(),
}, (t) => [index("jobs_business_status").on(t.businessId, t.status, t.createdAt)]);

// ---------- quotes ----------
export const quotes = pgTable("quotes", {
  id: id(),
  businessId: businessId(),
  jobId: uuid("job_id").references(() => jobs.id),   // null for quotes started by hand
  customerId: uuid("customer_id").notNull().references(() => customers.id),
  number: integer("number").notNull(),
  version: integer("version").notNull().default(1),
  parentQuoteId: uuid("parent_quote_id"),
  status: quoteStatus("status").notNull().default("draft"),
  discountCents: integer("discount_cents").notNull().default(0),
  subtotalCents: integer("subtotal_cents").notNull().default(0),
  taxCents: integer("tax_cents").notNull().default(0),
  totalCents: integer("total_cents").notNull().default(0),
  optionalTotalCents: integer("optional_total_cents").notNull().default(0),
  taxes: jsonb("taxes").$type<(TaxComponent & { amountCents: number })[]>().notNull().default([]),
  totalsComplete: boolean("totals_complete").notNull().default(false),  // false while any line needs a price
  terms: text("terms").notNull().default(""),
  depositPct: integer("deposit_pct").notNull().default(0),
  lockVersion: integer("lock_version").notNull().default(0),
  approvedBy: text("approved_by"),
  approvedAt: timestamp("approved_at", { withTimezone: true }),
  snapshot: jsonb("snapshot"),
  pdfObjectKey: text("pdf_object_key"),
  pdfSha256: text("pdf_sha256"),
  sentAt: timestamp("sent_at", { withTimezone: true }),
  sentVia: sentVia("sent_via"),
  providerEmailId: text("provider_email_id"),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
}, (t) => [
  unique("quotes_number_version").on(t.businessId, t.number, t.version),
  index("quotes_business_status").on(t.businessId, t.status),
  check("quotes_discount_bound", sql`${t.discountCents} >= 0 and ${t.discountCents} <= ${t.subtotalCents}`),
  check("quotes_total_identity", sql`${t.totalCents} = ${t.subtotalCents} - ${t.discountCents} + ${t.taxCents}`),
  check("quotes_money_nonneg", sql`${t.subtotalCents} >= 0 and ${t.taxCents} >= 0 and ${t.optionalTotalCents} >= 0`),
  check("quotes_deposit_pct", sql`${t.depositPct} between 0 and 100`),
]);

export const quoteLines = pgTable("quote_lines", {
  id: id(),
  businessId: businessId(),
  quoteId: uuid("quote_id").notNull().references(() => quotes.id, { onDelete: "cascade" }),
  sort: integer("sort").notNull(),
  description: text("description").notNull(),
  qtyMilli: integer("qty_milli").notNull(),
  unit: lineUnit("unit").notNull(),
  unitPriceCents: integer("unit_price_cents"),
  lineTotalCents: integer("line_total_cents"),
  priceBookItemId: uuid("price_book_item_id").references(() => priceBookItems.id, { onDelete: "set null" }),
  needsPrice: boolean("needs_price").notNull(),
  optional: boolean("optional").notNull().default(false),
  groupKey: text("group_key"),
  sourceKind: sourceKind("source_kind").notNull().default("manual"),
  sourceQuote: text("source_quote"),
  extractedSnapshot: jsonb("extracted_snapshot"),
}, (t) => [
  index("quote_lines_quote").on(t.quoteId, t.sort),
  check("quote_lines_qty", sql`${t.qtyMilli} > 0`),
  check("quote_lines_price", sql`${t.unitPriceCents} is null or ${t.unitPriceCents} >= 0`),
  check("quote_lines_needs_price", sql`${t.needsPrice} = (${t.unitPriceCents} is null)`),
]);

// ---------- invoices & payments ----------
export const invoices = pgTable("invoices", {
  id: id(),
  businessId: businessId(),
  quoteId: uuid("quote_id").notNull().references(() => quotes.id),
  kind: invoiceKind("kind").notNull(),
  number: integer("number").notNull(),
  status: invoiceStatus("status").notNull().default("issued"),
  dueDate: date("due_date"),                          // set on send
  amountCents: integer("amount_cents").notNull(),
  taxCents: integer("tax_cents").notNull(),
  paidCents: integer("paid_cents").notNull().default(0),
  snapshot: jsonb("snapshot").notNull(),
  pdfObjectKey: text("pdf_object_key"),
  pdfSha256: text("pdf_sha256"),
  providerEmailId: text("provider_email_id"),
  sentAt: timestamp("sent_at", { withTimezone: true }),
  remindersSent: integer("reminders_sent").notNull().default(0),
  createdAt: createdAt(),
}, (t) => [
  unique("invoices_quote_kind").on(t.quoteId, t.kind),
  unique("invoices_number").on(t.businessId, t.number),
  index("invoices_business_due").on(t.businessId, t.dueDate, t.status),
  check("invoices_paid_bound", sql`${t.paidCents} >= 0 and ${t.paidCents} <= ${t.amountCents}`),
]);

export const payments = pgTable("payments", {
  id: id(),
  businessId: businessId(),
  invoiceId: uuid("invoice_id").notNull().references(() => invoices.id),
  amountCents: integer("amount_cents").notNull(),     // negative = reversal of a wrong entry
  method: text("method").notNull(),
  receivedOn: date("received_on").notNull(),
  note: text("note"),
  recordedBy: text("recorded_by").notNull(),
  idempotencyKey: text("idempotency_key").notNull(),
  createdAt: createdAt(),
}, (t) => [unique("payments_idempotency").on(t.businessId, t.idempotencyKey)]);

